function pdf_template_clean_style(string $style): string {
    $allowed = [
        'font-family', 'font-size', 'font-weight', 'font-style', 'text-decoration',
        'color', 'background-color', 'text-align', 'vertical-align', 'width',
        'height', 'max-width', 'max-height', 'object-fit', 'border-radius', 'border', 'border-top', 'border-right',
        'border-bottom', 'border-left', 'border-collapse', 'padding', 'padding-top',
        'padding-right', 'padding-bottom', 'padding-left', 'margin', 'margin-top',
        'margin-right', 'margin-bottom', 'margin-left', 'line-height', 'display',
        'white-space',
    ];
    $safe = [];
    foreach (explode(';', $style) as $declaration) {
        if (strpos($declaration, ':') === false) continue;
        [$property, $value] = array_map('trim', explode(':', $declaration, 2));
        $property = strtolower($property);
        if (!in_array($property, $allowed, true) || $value === '') continue;
        if (!preg_match('/^[a-zA-Z0-9 #(),.%\\-]+$/', $value)) continue;
        $safe[] = $property . ':' . $value;
    }
    return implode(';', $safe);
}

function pdf_template_sanitize_html(string $html): string {
    $allowedTags = [
        'div', 'p', 'span', 'strong', 'b', 'em', 'i', 'u', 's', 'br', 'hr',
        'h1', 'h2', 'h3', 'h4', 'h5', 'h6', 'table', 'thead', 'tbody', 'tfoot',
        'tr', 'th', 'td', 'ol', 'ul', 'li', 'img', 'small', 'sup', 'sub',
    ];
    $previous = libxml_use_internal_errors(true);
    $document = new DOMDocument('1.0', 'UTF-8');
    $document->loadHTML('<?xml encoding="UTF-8"><div id="pdf-template-root">' . $html . '</div>', LIBXML_HTML_NOIMPLIED | LIBXML_HTML_NODEFDTD);
    $root = $document->getElementById('pdf-template-root');
    if (!$root) {
        libxml_clear_errors();
        libxml_use_internal_errors($previous);
        throw new RuntimeException('The template could not be parsed.');
    }
    $clean = static function (DOMNode $node) use (&$clean, $allowedTags): void {
        if ($node instanceof DOMElement) {
            $tag = strtolower($node->tagName);
            if (!in_array($tag, $allowedTags, true)) {
                $parent = $node->parentNode;
                if ($parent) {
                    while ($node->firstChild) $parent->insertBefore($node->firstChild, $node);
                    $parent->removeChild($node);
                }
                return;
            }
            $allowedAttributes = ['style', 'class', 'colspan', 'rowspan', 'width', 'height', 'src', 'alt'];
            for ($i = $node->attributes->length - 1; $i >= 0; $i--) {
                $attribute = $node->attributes->item($i);
                if (!$attribute) continue;
                $name = strtolower($attribute->name);
                if (!in_array($name, $allowedAttributes, true)) {
                    $node->removeAttributeNode($attribute);
                    continue;
                }
                if ($name === 'class') {
                    $allowedClasses = ['pdf-block', 'pdf-layout', 'pdf-phone-layout', 'pdf-keycard-layout'];
                    $classNames = preg_split('/\s+/', trim($attribute->value));
                    if (array_diff($classNames, $allowedClasses)) $node->removeAttribute($name);
                } elseif ($name === 'style') {
                    $node->setAttribute('style', pdf_template_clean_style($attribute->value));
                } elseif (in_array($name, ['colspan', 'rowspan', 'width', 'height'], true)) {
                    if (!preg_match('/^[0-9]{1,4}%?$/', $attribute->value)) $node->removeAttribute($name);
                } elseif ($name === 'src' && !in_array($attribute->value, ['ITIMS_COMPANY_LOGO', 'ITIMS_ASSET_PHOTO_URL'], true)) {
                    $node->removeAttribute($name);
                }
            }
            if ($tag === 'img' && !$node->hasAttribute('src')) {
                $node->parentNode->removeChild($node);
                return;
            }
        }
        $children = [];
        foreach ($node->childNodes as $child) $children[] = $child;
        foreach ($children as $child) $clean($child);
    };
    $children = [];
    foreach ($root->childNodes as $child) $children[] = $child;
    foreach ($children as $child) $clean($child);
    $result = '';
    foreach ($root->childNodes as $child) $result .= $document->saveHTML($child);
    libxml_clear_errors();
    libxml_use_internal_errors($previous);
    return $result;
}

function pdf_template_apply_fields(string $template, array $fields): string {
    foreach ($fields as $name => $value) {
        $template = str_replace('{{' . $name . '}}', (string)$value, $template);
        $template = str_replace('ITIMS_' . strtoupper($name), (string)$value, $template);
    }
    return $template;
}
